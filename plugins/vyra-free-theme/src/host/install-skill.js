/**
 * Skill + CLI shims installation (Host, best effort).
 *
 * Same shape as the screen-recorder plugin: the package ships a skill document
 * and two launcher scripts; on first run they are copied into the agent's skill
 * directory and into `$DSH_HOME/vyra-free-theme/bin/`. Everything is written
 * only when content differs, so a version bump rewrites and an unchanged run is
 * a no-op — and a read-only DSH_HOME never breaks the plugin.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const SKILL_NAME = "vyra-free-theme";

function writeIfChanged(file, content) {
  try {
    if (existsSync(file) && readFileSync(file, "utf8") === content) return false;
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, content, "utf8");
    return true;
  } catch {
    return false;
  }
}

function shellShim(nodePath, cliPath) {
  return `#!/bin/sh\n# vyra-free-theme CLI shim (generated by the plugin; do not edit)\nexec ${JSON.stringify(nodePath)} ${JSON.stringify(cliPath)} "$@"\n`;
}

function cmdShim(nodePath, cliPath) {
  return `@echo off\r\nrem vyra-free-theme CLI shim (generated by the plugin; do not edit)\r\n"${nodePath}" "${cliPath}" %*\r\n`;
}

/**
 * @param {{ dshHome: string, packageRoot: string, nodePath?: string }} options
 * @returns {{ skill: string|null, shims: string[] }}
 */
export function installSkillAndShims({ dshHome, packageRoot, nodePath = process.execPath }) {
  const result = { skill: null, shims: [] };
  const packageSkill = join(packageRoot, "skill", "SKILL.md");
  // Prefer the bundled CLI: the published package ships lib/ + cli/ but not
  // src/, and cli/vft.mjs imports the shared model. lib/cli.mjs is standalone.
  const bundledCli = join(packageRoot, "lib", "cli.mjs");
  const cliPath = existsSync(bundledCli) ? bundledCli : join(packageRoot, "cli", "vft.mjs");
  if (!existsSync(cliPath)) return result;

  if (existsSync(packageSkill)) {
    try {
      const content = readFileSync(packageSkill, "utf8");
      const target = join(dshHome, "skills", SKILL_NAME, "SKILL.md");
      if (writeIfChanged(target, content)) result.skill = target;
    } catch {}
  }

  const binDir = join(dshHome, SKILL_NAME, "bin");
  const sh = join(binDir, "vft");
  const cmd = join(binDir, "vft.cmd");
  try {
    if (writeIfChanged(sh, shellShim(nodePath, cliPath))) result.shims.push(sh);
    if (writeIfChanged(cmd, cmdShim(nodePath, cliPath))) result.shims.push(cmd);
  } catch {}

  return result;
}

export function packageRootFrom(importMetaUrl) {
  // src/index.js and lib/index.js both sit one level below the package root.
  return join(dirname(fileURLToPath(importMetaUrl)), "..");
}