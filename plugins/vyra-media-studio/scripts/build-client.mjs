/**
 * Bundle the browser half with esbuild, then wrap the CommonJS output in the
 * DSH module-loader factory so `require('react')` resolves through the shell's
 * shared module table. React and ReactDOM stay external; the lightbox and
 * lucide icons are bundled (both permissively licensed).
 */
import { build } from 'esbuild'
import { writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

const result = await build({
  entryPoints: [join(root, 'src/client/entry.js')],
  outfile: join(root, 'client.js'),
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: ['chrome100', 'safari15', 'firefox100'],
  external: ['react', 'react-dom', 'react-dom/client'],
  loader: { '.css': 'text' },
  define: { 'process.env.NODE_ENV': '"production"' },
  legalComments: 'inline',
  treeShaking: true,
  write: false,
})

const bundle = result.outputFiles[0].text
const wrapped = `/*
 * dsh-vyra-media-studio — generated by scripts/build-client.mjs.
 * Bundled with esbuild: yet-another-react-lightbox (MIT), lucide-react (ISC).
 * React/ReactDOM are supplied by the DSH client module table.
 */
window.__ModuleLoader__.load({
  id: 'dsh-vyra-media-studio',
  factory(require) {
    var module = { exports: {} }
    var exports = module.exports
    ;(function (require, module, exports) {
${bundle}
    })(require, module, exports)
    return module.exports && module.exports.default ? module.exports.default : module.exports
  },
})
`

await writeFile(join(root, 'client.js'), wrapped, 'utf8')
console.log(`client.js written (${(wrapped.length / 1024).toFixed(1)} KiB)`)
