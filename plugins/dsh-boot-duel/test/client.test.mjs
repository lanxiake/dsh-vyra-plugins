test('Esc leaves from every phase and is never swallowed', () => {
  const source = read('src/client.body.js')
  const onKeyDown = source.slice(source.indexOf('function onKeyDown(event)'))
  const escAt = onKeyDown.indexOf("event.code === 'Escape'")
  // Only another of the host's modals may keep Esc; a text field may not —
  // that was the reported "Esc does nothing" case.
  assert.ok(onKeyDown.indexOf('isForeignDialog(event.target)') < escAt)
  assert.ok(onKeyDown.indexOf('isTypingTarget(event.target)') > escAt)
  const escBlock = onKeyDown.slice(escAt, onKeyDown.indexOf('if (settled) {'))
  // Esc must finish() unconditionally, before every other game branch.
  assert.match(escBlock, /event\.preventDefault\(\)/)
  assert.match(escBlock, /event\.stopPropagation\(\)/)
  assert.match(escBlock, /session\.releaseAll\(\)/)
  assert.match(escBlock, /finish\(\)/)
  // No `if (event.code === 'Escape' && paused) return` dead-end survives.
  assert.doesNotMatch(onKeyDown, /'Escape' && paused/)
})

