test('the key handler reads pause state from the session, not a React variable', () => {
  const source = read('src/client.body.js')
  const mountLayer = source.slice(source.indexOf('function mountLayer('), source.indexOf('/** The `shell.overlay` entry'))
  assert.match(mountLayer, /session\.isPaused\(\)/)
  // `paused` is BootDuel's useState value; mountLayer is a sibling function, so
  // reading it there is a ReferenceError on every keystroke — the bug that made
  // the fight unplayable. Only `setPaused(...)` may be called from mountLayer.
  const reads = mountLayer.match(/(?<![.\w])paused(?![)\w])/g) || []
  assert.deepEqual(reads, [], 'mountLayer must not read the React `paused` variable')
})

test('the stage is one flat field, as in the reference', () => {
  const render = read('render.js')
  const stage = render.slice(render.indexOf('function paintStage(ctx)'), render.indexOf('function drawLimbChain('))
  // The reference's background is a single grey tone. Everything that would
  // break that — gradients, patterns, filters, composite grades — is absent.
  assert.ok(!/createLinearGradient|createRadialGradient|createPattern/.test(stage),
    'the stage must not gradient or tile')
  assert.ok(!/globalCompositeOperation|ctx.filter/.test(stage), 'the stage must not composite or blur')
  // It covers well past the arena so a camera move can never expose an edge.
  assert.match(stage, /fillRect\(-800, -600, 2600, 1600\)/)
  assert.match(stage, /fillStyle = INK.stage/)
})

test('there is no scenery, parallax, grading or grain left in the renderer', () => {
  const render = read('render.js')
  // Every one of these was an earlier attempt to add atmosphere. In a fight
  // drawn in two colours they all lower the contrast the silhouettes need.
  // Comments are stripped first: the source explains why each one is gone,
  // and that explanation must not itself count as a leftover.
  const code = render
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/^\s*\/\/.*$/gm, '')
  for (const gone of ['paintRidge', 'paintBamboo', 'paintMist', 'paintBlossom',
    'paintLanterns', 'paintInkBlots', 'paintFloor', 'paintStreaks', 'paintBackdrop',
    'grainTile', 'blurFor', 'soft-light', 'vignette']) {
    assert.ok(!code.includes(gone), `${gone} should be gone`)
  }
})

