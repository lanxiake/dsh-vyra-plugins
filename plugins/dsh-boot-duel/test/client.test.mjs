/**
 * A bundle client's factory only receives `require`. Referencing `host`,
 * `styles` or `console` as free variables throws a ReferenceError at run time,
 * which used to kill both the stylesheet and the config read — the root cause
 * of the layer rendering as a band over the chat list.
 */
test('the bundle never touches dynamic-run seats (host / styles)', () => {
  const source = read('src/client.body.js')
  assert.doesNotMatch(source, /\bstyles\.insert\(/, 'styles is not defined in a bundle client')
  assert.doesNotMatch(source, /\bhost\.call\(/, 'host is not defined in a bundle client')
  // The only route to config is the package's own webServer route.
  assert.match(source, /fetch\(CONFIG_URL/)
  assert.match(source, /const CONFIG_URL = '\/plugins\/dsh-boot-duel\/config'/)
})

