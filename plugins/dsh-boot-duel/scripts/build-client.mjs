/**
 * Build `client.js` from `src/client.body.js` plus the pure modules.
 *
 * Why a build step at all: the host loads the client half as ONE module
 * (`window.__ModuleLoader__.load({ id, factory })`), and the browser module
 * table offers no way to `require` a sibling file inside a package. So the
 * simulation modules that `node --test` imports directly have to be inlined
 * into the factory scope here.
 *
 * The modules stay separate files on disk — that is what keeps them testable
 * without a bundler and without installing any dependency.
 *
 * Usage:
 *   node scripts/build-client.mjs           regenerate client.js
 *   node scripts/build-client.mjs --check   fail if client.js is stale
 */
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const scripts = path.dirname(fileURLToPath(import.meta.url))
const root = path.dirname(scripts)
const read = (file) => readFileSync(path.join(root, file), 'utf8')

/** Modules inlined into the factory, in dependency order. */
const MODULES = [
  // Dependency order: the rig has no imports, the fighter needs it, combat
  // needs both, the arena needs all three, and the adapter is the facade.
  { file: 'js/rig.js', name: 'rig' },
  { file: 'js/juice.js', name: 'juice' },
  { file: 'js/fighter.js', name: 'fighter' },
  { file: 'js/story.js', name: 'story' },
  { file: 'js/combat.js', name: 'combat' },
  { file: 'js/arena.js', name: 'arena' },
  { file: 'js/adapter.js', name: 'duel' },
  { file: 'js/backdrop.js', name: 'backdrop' },
  { file: 'js/effects.js', name: 'effects' },
  { file: 'js/render.js', name: 'render' },
  { file: 'js/audio.js', name: 'audio' },
  { file: 'js/loop.js', name: 'loop' },
  // The session controller is unchanged and still guards every exit path.
  { file: 'sim/session.mjs', name: 'session' },
]

/**
 * Rewrite one ESM module into a CJS-style body the factory can evaluate:
 *
 *   import { a, b } from './x.mjs'   ->  const { a, b } = __mod_x
 *   import x from './x.mjs'          ->  const x = __mod_x
 *   export const NAME = ...          ->  const NAME = ...
 *   export function NAME(...)        ->  function NAME(...)
 *   export { ... }                   ->  (dropped; the module map exports by name)
 *
 * Only the import/export forms these modules actually use are supported, and
 * anything unexpected throws loudly instead of producing a broken bundle.
 */
function transform(source, resolveModule) {
  let out = source

  // Named and default imports.
  out = out.replace(
    /^import\s+(?:\{([^}]*)\}|\*\s+as\s+(\w+)|(\w+))\s+from\s+['"](\.[^'"]+)['"];?$/gm,
    (whole, named, star, defaultName, specifier) => {
      const key = resolveModule(specifier)
      if (!key) throw new Error(`cannot inline unknown import: ${specifier}`)
      if (named) return `const {${named}} = __mod_${key};`
      if (star) return `const ${star} = __mod_${key};`
      return `const ${defaultName} = __mod_${key};`
    },
  )

  // Exports become plain declarations; the module map collects them.
  out = out.replace(/^export\s+const\s+/gm, 'const ')
  out = out.replace(/^export\s+let\s+/gm, 'let ')
  out = out.replace(/^export\s+function\s+/gm, 'function ')
  out = out.replace(/^export\s+async\s+function\s+/gm, 'async function ')
  out = out.replace(/^export\s+class\s+/gm, 'class ')
  // Trailing `export { a, b }` re-exports carry nothing we need: every name is
  // already a declaration in this scope.
  out = out.replace(/^export\s+\{[^}]*\};?\s*$/gms, '')

  if (/^\s*(import|export)\s/m.test(out)) {
    throw new Error(`unsupported module syntax left after transform:\n${out.match(/^\s*(?:import|export)\s.*$/m)?.[0]}`)
  }
  return out.trim()
}

function build() {
  // Imports are written relative to the importing file, e.g. './constants.mjs'
  // from sim/fighter.mjs, so resolve by basename.
  const byBase = new Map(MODULES.map((entry) => [path.basename(entry.file), entry.name]))
  const resolveModule = (specifier) => byBase.get(path.basename(specifier))

  const bodies = MODULES.map((entry) => {
    const source = read(entry.file)
    const body = transform(source, resolveModule)
    return `  /* ---- ${entry.file} ---- */\n  const __mod_${entry.name} = (function () {\n${indent(body, 4)}\n    return { ${exportNames(source).join(', ')} };\n  })();`
  })

  const body = read('src/client.body.js')
  const marker = '    /* __INLINED_MODULES__ */'
  if (!body.includes(marker)) throw new Error('src/client.body.js is missing the inline marker')

  const generated = body.replace(marker, bodies.join('\n\n'))

  const target = path.join(root, 'client.js')
  const header = `/* Generated by scripts/build-client.mjs from src/client.body.js + sim/*.mjs + render.js. Do not edit by hand. */\n`
  const output = header + generated

  if (process.argv.includes('--check')) {
    const current = readFileSync(target, 'utf8')
    if (current !== output) {
      console.error('client.js is stale; run: node scripts/build-client.mjs')
      process.exit(1)
    }
    console.log(`client.js is up to date (${output.length} bytes)`)
    return
  }

  writeFileSync(target, output)
  console.log(`wrote client.js (${output.length} bytes)`)
}

/** Names a module exports, for building its returned object literal. */
function exportNames(source) {
  const names = new Set()
  for (const match of source.matchAll(/^export\s+(?:const|let|function|async\s+function|class)\s+(\w+)/gm)) {
    names.add(match[1])
  }
  for (const match of source.matchAll(/^export\s+\{([^}]*)\};?$/gm)) {
    for (const part of match[1].split(',')) {
      const cleaned = part.trim()
      if (!cleaned) continue
      const [local, alias] = cleaned.split(/\s+as\s+/).map((piece) => piece.trim())
      names.add(alias || local)
    }
  }
  return [...names]
}

function indent(text, spaces) {
  const pad = ' '.repeat(spaces)
  return text.split('\n').map((line) => (line.length ? pad + line : line)).join('\n')
}

build()
