#!/usr/bin/env node
/**
 * Bundle Folia's pure track-profile analysis for the browser client.
 *
 *   node scripts/build-profile.mjs
 *   node scripts/build-profile.mjs --check
 */
import { build } from 'esbuild'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(ROOT, 'src/client/services/automix/profile.bundle.js')
const CHECK = process.argv.includes('--check')

if (CHECK && !existsSync(OUT)) {
  console.error('src/client/services/automix/profile.bundle.js is missing; run node scripts/build-profile.mjs')
  process.exit(1)
}

const result = await build({
  entryPoints: [join(ROOT, 'src/client/services/automix/entry.ts')],
  write: false,
  bundle: true,
  format: 'iife',
  globalName: 'MPProfile',
  platform: 'browser',
  target: ['chrome120'],
  minify: false,
  logLevel: 'silent',
  loader: { '.ts': 'ts' },
}).catch((error) => {
  const errors = error.errors || []
  console.error(`profile bundle failed: ${errors.length} error(s)`)
  for (const item of errors.slice(0, 40)) {
    const where = item.location
      ? `${item.location.file.replace(ROOT + '\\', '').replace(ROOT + '/', '')}:${item.location.line} `
      : ''
    console.error(`  ${where}${item.text}`)
  }
  if (errors.length === 0) console.error(String(error && error.message ? error.message : error))
  process.exit(1)
})

const text = result.outputFiles[0].text.replace(/\n/g, '\n  ')
const output = `/**
 * Folia track-profile analysis — generated by scripts/build-profile.mjs.
 * Never edit this file by hand.
 */
function __mpProfileBundle() {
  ${text}
  return typeof MPProfile === 'undefined' ? null : MPProfile
}
`

if (CHECK) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
  if (current !== output) {
    console.error('src/client/services/automix/profile.bundle.js is stale; run node scripts/build-profile.mjs')
    process.exit(1)
  }
  console.log('profile bundle up to date')
} else {
  writeFileSync(OUT, output)
  console.log('profile bundle written:', OUT)
}
